-- App Database Schema for QueryPilot
-- Stores conversations, query history, and evaluation run results
-- This is separate from the Target DB (which is read-only analytics data)

-- Conversations table: chat sessions
CREATE TABLE IF NOT EXISTS conversations (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id VARCHAR(255) NOT NULL,
    title VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE conversations IS 'Chat sessions; one row per conversation thread.';
COMMENT ON COLUMN conversations.id IS 'Unique conversation identifier (UUID).';
COMMENT ON COLUMN conversations.user_id IS 'User who created the conversation.';
COMMENT ON COLUMN conversations.title IS 'Optional title or topic for the conversation.';
COMMENT ON COLUMN conversations.created_at IS 'Timestamp when conversation was started.';
COMMENT ON COLUMN conversations.updated_at IS 'Timestamp of last message in conversation.';

-- Query Log table: all queries executed
CREATE TABLE IF NOT EXISTS query_log (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    conversation_id UUID REFERENCES conversations(id) ON DELETE SET NULL,
    user_id VARCHAR(255),
    question TEXT NOT NULL,
    provider VARCHAR(50),
    model VARCHAR(100),
    generated_sql TEXT,
    execution_time_ms INT,
    tokens_used INT,
    result_row_count INT,
    error_type VARCHAR(50),
    error_message TEXT,
    metadata JSONB,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE query_log IS 'Durable log of all queries; one row per question+answer.';
COMMENT ON COLUMN query_log.id IS 'Unique query log entry ID.';
COMMENT ON COLUMN query_log.timestamp IS 'When the query was processed.';
COMMENT ON COLUMN query_log.conversation_id IS 'FK to conversations; which conversation this query belongs to.';
COMMENT ON COLUMN query_log.user_id IS 'User who asked the question.';
COMMENT ON COLUMN query_log.question IS 'Natural-language question.';
COMMENT ON COLUMN query_log.provider IS 'LLM provider (openai, anthropic, bedrock).';
COMMENT ON COLUMN query_log.model IS 'LLM model (gpt-4, claude-3, etc.).';
COMMENT ON COLUMN query_log.generated_sql IS 'SQL generated by LLM or agent.';
COMMENT ON COLUMN query_log.execution_time_ms IS 'Query execution time in milliseconds.';
COMMENT ON COLUMN query_log.tokens_used IS 'LLM tokens used for this query (if available).';
COMMENT ON COLUMN query_log.result_row_count IS 'Number of rows returned.';
COMMENT ON COLUMN query_log.error_type IS 'Type of error (if any): syntax_error, timeout, permission_error, etc.';
COMMENT ON COLUMN query_log.error_message IS 'Sanitized error message (no credentials).';
COMMENT ON COLUMN query_log.metadata IS 'JSON metadata: phases, latencies, retry counts, etc.';
COMMENT ON COLUMN query_log.created_at IS 'System timestamp.';

CREATE INDEX idx_query_log_conversation_id ON query_log(conversation_id);
CREATE INDEX idx_query_log_user_id ON query_log(user_id);
CREATE INDEX idx_query_log_timestamp ON query_log(timestamp);
CREATE INDEX idx_query_log_provider ON query_log(provider);

-- Evaluation Runs table: baseline and agent evaluation results
CREATE TABLE IF NOT EXISTS eval_runs (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    run_timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    baseline_provider VARCHAR(50),
    baseline_model VARCHAR(100),
    overall_accuracy DECIMAL(5, 4),
    category_breakdown JSONB,
    error_rate DECIMAL(5, 4),
    error_breakdown JSONB,
    total_items INT,
    matches INT,
    errors INT,
    full_results JSONB,
    metadata JSONB,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE eval_runs IS 'Evaluation run results; one row per baseline or agent evaluation.';
COMMENT ON COLUMN eval_runs.id IS 'Unique evaluation run ID.';
COMMENT ON COLUMN eval_runs.run_timestamp IS 'When the evaluation run started.';
COMMENT ON COLUMN eval_runs.baseline_provider IS 'LLM provider used for baseline.';
COMMENT ON COLUMN eval_runs.baseline_model IS 'LLM model used for baseline.';
COMMENT ON COLUMN eval_runs.overall_accuracy IS 'Accuracy as decimal (0.0 to 1.0).';
COMMENT ON COLUMN eval_runs.category_breakdown IS 'JSON: {category: accuracy_pct} for each category.';
COMMENT ON COLUMN eval_runs.error_rate IS 'Fraction of items that resulted in errors.';
COMMENT ON COLUMN eval_runs.error_breakdown IS 'JSON: {error_type: count} for each error type.';
COMMENT ON COLUMN eval_runs.total_items IS 'Total number of evaluation items.';
COMMENT ON COLUMN eval_runs.matches IS 'Number of items with correct results.';
COMMENT ON COLUMN eval_runs.errors IS 'Number of items with errors.';
COMMENT ON COLUMN eval_runs.full_results IS 'JSON array of all result items (question, sql, match, error).';
COMMENT ON COLUMN eval_runs.metadata IS 'JSON metadata: duration, seed, phase, etc.';
COMMENT ON COLUMN eval_runs.created_at IS 'System timestamp.';

CREATE INDEX idx_eval_runs_run_timestamp ON eval_runs(run_timestamp);
CREATE INDEX idx_eval_runs_baseline_provider ON eval_runs(baseline_provider);
